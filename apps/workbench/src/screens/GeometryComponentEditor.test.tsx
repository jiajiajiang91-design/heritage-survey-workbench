import { act, cleanup, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, describe, expect, it, vi } from "vitest";
import { GeometryComponentEditor, ComponentInputPanel } from "./GeometryComponentEditor";
import { componentFixture } from "../test/component-fixture";
import { componentCandidateFixture } from "../test/component-candidate-fixture";
import { FactEnvelopeSchema } from "@gujian/domain";
vi.mock("../DraftGeometryViewer", () => ({ DraftGeometryViewer: ({ component, onSelect }: { component: { stableKey: string }; onSelect: (key: string) => void }) => <button type="button" onClick={() => onSelect(component.stableKey)}>选择待核对形体</button> }));
Object.defineProperty(Element.prototype, "scrollIntoView", { value: vi.fn(), configurable: true });
afterEach(cleanup);
async function setup(save = vi.fn().mockResolvedValue(true)) {
  const test = await componentFixture();
  const componentFact = FactEnvelopeSchema.parse({ ...test.dimension, id: crypto.randomUUID(), field: "geometry.component." + test.component.stableKey, value: test.component });
  test.head.snapshot.facts.push(componentFact);
  const props = { snapshot: test.head.snapshot, base: test.component, onSave: save, onCancel: vi.fn(), onShowEvidence: vi.fn() };
  return { ...test, props, save, view: render(<GeometryComponentEditor {...props} />) };
}
async function crossEvidenceFixture() {
  const test = await componentCandidateFixture();
  const sourceB = test.head.snapshot.evidences[0]!;
  const sourceA = { ...sourceB, id: crypto.randomUUID(), title: "构件A图" };
  test.head.snapshot.evidences.push(sourceA);
  test.head.snapshot.parseRecords.push({ ...test.head.snapshot.parseRecords[0]!, id: crypto.randomUUID(), evidenceId: sourceA.id });
  const candidate = test.head.snapshot.candidates.find((item) => item.id === test.recognition.id)!;
  if (candidate.structured?.kind !== "componentRecognition") throw new Error("测试构件候选缺失");
  candidate.structured.components[0]!.evidenceRef = sourceA.id;
  candidate.evidenceRefs = [sourceA.id];
  const dimensionCandidate = test.head.snapshot.candidates.find((item) => item.id === test.candidate.id)!;
  if (dimensionCandidate.structured?.kind !== "measurementTranscription") throw new Error("测试尺寸候选缺失");
  const parameterRegion = { x: .2, y: .6, width: .3, height: .1 };
  dimensionCandidate.structured.dimensions[1]!.region = parameterRegion;
  const component = { ...test.inputs[0]!, evidenceRefs: [sourceB.id, sourceA.id] };
  test.head.snapshot.facts.push(FactEnvelopeSchema.parse({ ...test.dimension, id: crypto.randomUUID(), field: "geometry.component." + component.stableKey, value: component }));
  return { ...test, component, sourceA, sourceB, parameterRegion };
}
describe("普通构件表单", () => {
  it("选择已采用尺寸后显示只读数值与资料，候选保留待核对标记", async () => {
    const test = await setup();
    const select = screen.getByLabelText("X 向长度来源");
    expect(select).toHaveTextContent("总宽"); expect(select).toHaveTextContent("总深"); expect(select).toHaveTextContent("待核对");
    fireEvent.change(select, { target: { value: test.dimension.id } });
    expect(screen.getByLabelText("X 向长度（mm）")).toHaveValue("6000");
    expect(screen.getByLabelText("X 向长度（mm）")).toHaveAttribute("readonly");
    fireEvent.click(screen.getByRole("button", { name: "查看：内部测试尺寸.txt" }));
    expect(test.props.onShowEvidence).toHaveBeenCalledWith(test.dimension.evidenceRefs[0]);
    fireEvent.click(screen.getByRole("button", { name: "保存构件输入" }));
    await waitFor(() => expect(test.save).toHaveBeenCalledOnce());
    expect(test.save.mock.calls[0]![0].dimensionBindings).toEqual([{ field: "sizeX", sourceFactRef: test.dimension.id }]);
    expect(test.props.onCancel).toHaveBeenCalledOnce();
  });
  it("无效长度定位到字段并阻止写入，取消不保存", async () => {
    const test = await setup();
    fireEvent.change(screen.getByLabelText("X 向长度（mm）"), { target: { value: "0" } });
    fireEvent.click(screen.getByRole("button", { name: "保存构件输入" }));
    await waitFor(() => expect(screen.getByLabelText("X 向长度（mm）")).toHaveFocus());
    expect(screen.getByLabelText("X 向长度（mm）")).toHaveAttribute("aria-invalid", "true");
    expect(test.save).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole("button", { name: "取消" }));
    expect(test.props.onCancel).toHaveBeenCalledOnce(); expect(test.save).not.toHaveBeenCalled();
  });
  it("保存中阻止重复提交，失败及异常保留全部草稿", async () => {
    let finish!: (value: boolean) => void;
    const save = vi.fn().mockImplementationOnce(() => new Promise<boolean>((resolve) => { finish = resolve; })).mockRejectedValueOnce(new Error("WRITE_FAILED"));
    const test = await setup(save);
    fireEvent.change(screen.getByLabelText("构件名称"), { target: { value: "更名墙体" } });
    fireEvent.click(screen.getByRole("button", { name: "保存构件输入" }));
    fireEvent.submit(screen.getByRole("form", { name: "构件参数" }));
    expect(save).toHaveBeenCalledOnce(); expect(screen.getByLabelText("构件名称")).toBeDisabled();
    await act(async () => finish(false));
    expect(screen.getByLabelText("构件名称")).toHaveValue("更名墙体");
    expect(test.props.onCancel).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole("button", { name: "保存构件输入" }));
    await waitFor(() => expect(save).toHaveBeenCalledTimes(2));
    expect(screen.getByLabelText("构件名称")).toHaveValue("更名墙体");
    expect(screen.getByRole("status")).toHaveTextContent("草稿已保留");
  });
  it("可切换圆柱和逐点挤出表单，长度不自动补齐", async () => {
    await setup();
    fireEvent.change(screen.getByLabelText("实体形式"), { target: { value: "cylinder" } });
    expect(screen.getByLabelText("半径（mm）")).toHaveValue("");
    expect(screen.getByLabelText("圆柱长度（mm）")).toHaveValue("");
    fireEvent.change(screen.getByLabelText("实体形式"), { target: { value: "extrudedProfile" } });
    expect(screen.getByLabelText("挤出长度（mm）")).toHaveValue("");
    expect(screen.getByLabelText("点 1 U")).toHaveValue("");
    fireEvent.click(screen.getByRole("button", { name: "增加轮廓点" }));
    expect(screen.getByLabelText("点 4 V")).toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: "移除点 4" }));
    expect(screen.queryByLabelText("点 4 V")).not.toBeInTheDocument();
  });
  it("同一构件记录变化时锁定旧草稿，取消后可重开", async () => {
    const test = await setup();
    const snapshot = structuredClone(test.head.snapshot);
    snapshot.facts.push({ ...snapshot.facts.at(-1)!, id: crypto.randomUUID(), value: { ...test.component, displayNameZh: "另一处修订" } });
    test.view.rerender(<GeometryComponentEditor {...test.props} snapshot={snapshot} />);
    expect(screen.getByLabelText("构件名称")).toHaveValue("内部测试墙");
    expect(screen.getByLabelText("构件名称")).toBeDisabled();
    fireEvent.click(screen.getByRole("button", { name: "取消编辑" }));
    expect(test.props.onCancel).toHaveBeenCalledOnce(); expect(test.save).not.toHaveBeenCalled();
  });
  it("展示模型没有输入时不提供新增或反写入口", async () => {
    const test = await componentFixture();
    test.head.snapshot.geometrySpecs = [{} as typeof test.head.snapshot.geometrySpecs[number]];
    const save = vi.fn();
    render(<ComponentInputPanel snapshot={test.head.snapshot} onSave={save} onShowEvidence={vi.fn()} />);
    expect(screen.queryByRole("button", { name: "新增构件输入" })).not.toBeInTheDocument();
    expect(screen.getByText(/没有原始构件输入记录/)).toBeInTheDocument();
    expect(save).not.toHaveBeenCalled();
  });
  it("预览、选择来源和修改保持草稿，不保存事实且旧形体立即失效", async () => {
    const test = await setup();
    fireEvent.change(screen.getByLabelText("材料"), { target: { value: "" } });
    fireEvent.click(screen.getByRole("button", { name: "预览待核对形体" }));
    expect(screen.getByLabelText("待核对形体预览")).toHaveTextContent("材料：未知");
    fireEvent.click(screen.getByRole("button", { name: "选择待核对形体" }));
    expect(test.props.onShowEvidence).toHaveBeenCalledWith(test.component.evidenceRefs[0]);
    expect(screen.getByLabelText("预览参数来源")).toHaveFocus();
    expect(test.save).not.toHaveBeenCalled();
    fireEvent.change(screen.getByLabelText("X 向长度（mm）"), { target: { value: "6100.5" } });
    expect(screen.queryByLabelText("待核对形体预览")).not.toBeInTheDocument();
    expect(screen.getByRole("status")).toHaveTextContent("旧形体已清除");
    expect(screen.getByLabelText("X 向长度（mm）")).toHaveValue("6100.5");
    fireEvent.click(screen.getByRole("button", { name: "预览待核对形体" }));
    expect(screen.getByLabelText("预览参数来源")).toHaveTextContent("当前值：6100.5 mm");
  });
  it("raw 候选可修正并通过原子保存入口提交，清来源恢复普通入口", async () => {
    const test = await setup();
    const saveDraft = vi.fn().mockResolvedValue(false);
    test.view.rerender(<GeometryComponentEditor {...test.props} onSaveDraft={saveDraft} />);
    fireEvent.change(screen.getByLabelText("X 向长度来源"), { target: { value: `candidate:${test.candidate.id}:1` } });
    expect(screen.getByLabelText("X 向长度（mm）")).toHaveValue("4200");
    expect(screen.getByLabelText("X 向长度（mm）")).not.toHaveAttribute("readonly");
    expect(screen.getByText("待核对候选 · 类型待核对")).toBeInTheDocument();
    expect(screen.getByText(/本次用于X 向长度/)).toBeInTheDocument();
    fireEvent.change(screen.getByLabelText("X 向长度（mm）"), { target: { value: "4100.5" } });
    fireEvent.change(screen.getByLabelText("候选尺寸核对说明"), { target: { value: "按原资料核对，本字段用于 X 向长度并修正读数" } });
    fireEvent.click(screen.getByRole("button", { name: "预览待核对形体" }));
    expect(screen.getByLabelText("预览参数来源")).toHaveTextContent("原标注：4200");
    expect(screen.getByLabelText("预览参数来源")).toHaveTextContent("当前值：4100.5 mm");
    expect(saveDraft).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole("button", { name: "核对并保存构件输入" }));
    await waitFor(() => expect(saveDraft).toHaveBeenCalledOnce());
    const draft = saveDraft.mock.calls[0]![0];
    expect(draft.candidateBindings.sizeX).toEqual({ candidateId: test.candidate.id, rowIndex: 1 });
    expect(draft.bindings.sizeX).toBeUndefined(); expect(draft.lengths.sizeX).toBe("4100.5");
    expect(test.save).not.toHaveBeenCalled(); expect(test.props.onCancel).not.toHaveBeenCalled();
    fireEvent.change(screen.getByLabelText("X 向长度来源"), { target: { value: "" } });
    expect(screen.getByRole("button", { name: "保存构件输入" })).toBeInTheDocument();
    expect(screen.queryByLabelText("候选尺寸核对说明")).not.toBeInTheDocument();
  });
  it("快照来源改变即隐藏旧预览，重新预览列明失效引用，缺项保留输入", async () => {
    const test = await setup();
    fireEvent.change(screen.getByLabelText("X 向长度来源"), { target: { value: `candidate:${test.candidate.id}:1` } });
    fireEvent.click(screen.getByRole("button", { name: "预览待核对形体" }));
    expect(screen.getByLabelText("待核对形体预览")).toBeInTheDocument();
    const snapshot = structuredClone(test.head.snapshot);
    snapshot.candidates.find((candidate) => candidate.id === test.candidate.id)!.reviewStatus = "rejected";
    test.view.rerender(<GeometryComponentEditor {...test.props} snapshot={snapshot} />);
    expect(screen.queryByLabelText("待核对形体预览")).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole("button", { name: "预览待核对形体" }));
    expect(screen.getByLabelText("X 向长度（mm）")).toHaveAttribute("aria-invalid", "true");
    expect(screen.getByLabelText("X 向长度（mm）")).toHaveValue("4200");
    fireEvent.change(screen.getByLabelText("X 向长度来源"), { target: { value: "" } });
    fireEvent.change(screen.getByLabelText("Z 坐标"), { target: { value: "" } });
    fireEvent.click(screen.getByRole("button", { name: "预览待核对形体" }));
    expect(screen.getByLabelText("Z 坐标")).toHaveAttribute("aria-invalid", "true");
    expect(screen.getByLabelText("构件名称")).toHaveValue("内部测试墙");
    expect(test.save).not.toHaveBeenCalled();
  });
  it.each(["candidate", "adopted"] as const)("仅解析记录变化时 %s 来源旧形体立即失效且草稿保留", async (kind) => {
    const test = await setup();
    fireEvent.change(screen.getByLabelText("X 向长度来源"), { target: { value: kind === "candidate" ? `candidate:${test.candidate.id}:1` : test.dimension.id } });
    fireEvent.click(screen.getByRole("button", { name: "预览待核对形体" }));
    expect(screen.getByLabelText("待核对形体预览")).toBeInTheDocument();
    const snapshot = structuredClone(test.head.snapshot);
    snapshot.parseRecords.push({ ...snapshot.parseRecords[0]!, id: crypto.randomUUID(), status: "failed", readability: kind === "candidate" ? "failed" : "unsupported" });
    expect(snapshot.candidates).toEqual(test.head.snapshot.candidates);
    expect(snapshot.evidences).toEqual(test.head.snapshot.evidences);
    expect(snapshot.facts).toEqual(test.head.snapshot.facts);
    test.view.rerender(<GeometryComponentEditor {...test.props} snapshot={snapshot} />);
    expect(screen.queryByLabelText("待核对形体预览")).not.toBeInTheDocument();
    expect(screen.getByRole("status")).toHaveTextContent("旧形体已清除");
    fireEvent.click(screen.getByRole("button", { name: "预览待核对形体" }));
    expect(screen.getByLabelText("X 向长度（mm）")).toHaveAttribute("aria-invalid", "true");
    expect(screen.getByLabelText("X 向长度（mm）")).toHaveValue(kind === "candidate" ? "4200" : "6000");
    expect(test.save).not.toHaveBeenCalled();
  });
  it("跨资料形体选择恢复构件A图候选区域，参数按钮独立查看B表", async () => {
    const test = await crossEvidenceFixture();
    const show = vi.fn(), select = vi.fn(), save = vi.fn();
    render(<ComponentInputPanel snapshot={test.head.snapshot} onSave={save} onShowEvidence={show} onSelectCandidate={select} />);
    fireEvent.click(screen.getByRole("button", { name: "编辑识别构件：内部墙体" }));
    fireEvent.change(screen.getByLabelText("X 向长度来源"), { target: { value: `candidate:${test.candidate.id}:1` } });
    fireEvent.click(screen.getByRole("button", { name: "查看候选原件：" + test.sourceB.title }));
    expect(show).toHaveBeenLastCalledWith(test.sourceB.id, test.parameterRegion);
    fireEvent.click(screen.getByRole("button", { name: "预览待核对形体" }));
    show.mockClear(); select.mockClear();
    fireEvent.click(screen.getByRole("button", { name: "选择待核对形体" }));
    expect(show).toHaveBeenLastCalledWith(test.sourceA.id);
    expect(select).toHaveBeenLastCalledWith(test.component.candidateSource);
    expect(screen.getByLabelText("预览参数来源")).toHaveFocus();
    fireEvent.click(screen.getAllByRole("button", { name: "查看参数原件：" + test.sourceB.title })[0]!);
    expect(show).toHaveBeenLastCalledWith(test.sourceB.id, test.parameterRegion);
    expect(save).not.toHaveBeenCalled();
  });
  it("首次编辑和重开已保存candidateSource输入均恢复构件A图区域", async () => {
    const test = await crossEvidenceFixture();
    const show = vi.fn(), select = vi.fn();
    render(<ComponentInputPanel snapshot={test.head.snapshot} onSave={vi.fn()} onShowEvidence={show} onSelectCandidate={select} />);
    for (let attempt = 0; attempt < 2; attempt++) {
      show.mockClear(); select.mockClear();
      fireEvent.click(screen.getByRole("button", { name: "编辑识别构件：内部墙体" }));
      expect(select).toHaveBeenCalledExactlyOnceWith(test.component.candidateSource);
      expect(show).toHaveBeenLastCalledWith(test.sourceA.id);
      expect(screen.getByLabelText("X 向长度（mm）")).toHaveValue("6000");
      fireEvent.click(screen.getByRole("button", { name: "取消" }));
    }
  });
});
